public class Color {
    public static final String RESET   = "\u001B[0m";
    public static final String RED     = "\u001B[31m";   // 红字
    public static final String YELLOW  = "\u001B[93m";
    public static final String BOLD    = "\u001B[1m";    // 加粗
    public static final String BG_WHITE= "\u001B[47m";   // 白底
    public static final String GRAY    = "\u001B[90m";   // 暗色（楚河汉界）
}
